public void refreshInstructorList() {

    jPanel3.removeAll();

    jPanel3.setLayout(
            new javax.swing.BoxLayout(
                    jPanel3,
                    javax.swing.BoxLayout.Y_AXIS
            )
    );

    for (UserUI instructor : instructorList) {

        UserRow row =
                new UserRow(
                        instructor,
                        instructorList,
                        this::refreshInstructorList
                );

        row.setAlignmentX(LEFT_ALIGNMENT);

        jPanel3.add(row);

        jPanel3.add(
                javax.swing.Box.createRigidArea(
                        new java.awt.Dimension(0, 10)
                )
        );
    }

    jPanel3.revalidate();

    jPanel3.repaint();
}
public void refreshFilteredList(ArrayList<UserUI> list) {

    jPanel3.removeAll();

    jPanel3.setLayout(
            new javax.swing.BoxLayout(
                    jPanel3,
                    javax.swing.BoxLayout.Y_AXIS
            )
    );

    for (UserUI instructor : list) {

        UserRow row = new UserRow(
                instructor,
                instructorList,
                this::refreshInstructorList
        );

        jPanel3.add(row);
        jPanel3.add(javax.swing.Box.createRigidArea(
                new java.awt.Dimension(0, 10)
        ));
    }

    jPanel3.revalidate();
    jPanel3.repaint();
}
    


